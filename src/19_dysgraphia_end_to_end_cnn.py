"""Independent end-to-end CNN baseline for the dysgraphia task.

Uses the exact image-level split tensors generated by dysgraphia_pipeline.py,
then independently initializes/trains a CNN classifier without external ML
classifiers or a stacking meta-learner. It never overwrites the feature extractor.
"""
from pathlib import Path
import json
import numpy as np
import os
os.environ["CUDA_VISIBLE_DEVICES"] = "-1"
os.environ.setdefault("TF_DETERMINISTIC_OPS", "1")
import tensorflow as tf
from sklearn.metrics import (accuracy_score, precision_score, recall_score,
    f1_score, roc_auc_score, confusion_matrix, classification_report, log_loss)
from config import OUTPUT_ROOT, SEED

ROOT = Path(__file__).resolve().parents[1]
SPLIT = OUTPUT_ROOT / "splits" / "dysgraphia"
OUT = OUTPUT_ROOT / "results" / "dysgraphia_end_to_end_cnn"
MODEL_DIR = OUTPUT_ROOT / "models" / "dysgraphia_end_to_end_cnn"
OUT.mkdir(parents=True, exist_ok=True)
MODEL_DIR.mkdir(parents=True, exist_ok=True)


def main():
    tf.keras.utils.set_random_seed(SEED)
    required = [SPLIT / n for n in ("X_train_cnn.npy", "y_train.npy", "X_val_cnn.npy", "y_val.npy", "X_test_cnn.npy", "y_test.npy")]
    missing = [str(p) for p in required if not p.exists()]
    if missing:
        raise FileNotFoundError("Run the main dysgraphia pipeline first. Missing split artifacts: " + ", ".join(missing))
    X_train, y_train, X_val, y_val, X_test, y_test = [np.load(p) for p in required]
    model = tf.keras.Sequential([
        tf.keras.layers.Input(shape=(28, 28, 1)),
        tf.keras.layers.Conv2D(32, (3, 3), activation="relu", padding="same"),
        tf.keras.layers.MaxPooling2D((2, 2)),
        tf.keras.layers.Conv2D(64, (3, 3), activation="relu", padding="same"),
        tf.keras.layers.MaxPooling2D((2, 2)),
        tf.keras.layers.Flatten(),
        tf.keras.layers.Dense(128, activation="relu"),
        tf.keras.layers.Dropout(0.3),
        tf.keras.layers.Dense(2, activation="softmax"),
    ])
    model.compile(optimizer=tf.keras.optimizers.Adam(1e-3), loss="sparse_categorical_crossentropy", metrics=["accuracy"])
    hist = model.fit(X_train, y_train, validation_data=(X_val, y_val), epochs=20,
        batch_size=64, callbacks=[tf.keras.callbacks.EarlyStopping(monitor="val_loss", patience=5, restore_best_weights=True)], verbose=1)
    proba = model.predict(X_test, verbose=0)
    pred = np.argmax(proba, axis=1)
    metrics = {
        "n_test": int(len(y_test)), "accuracy": float(accuracy_score(y_test, pred)),
        "macro_precision": float(precision_score(y_test, pred, average="macro", zero_division=0)),
        "macro_recall": float(recall_score(y_test, pred, average="macro", zero_division=0)),
        "macro_f1": float(f1_score(y_test, pred, average="macro", zero_division=0)),
        "roc_auc": float(roc_auc_score(y_test, proba[:, 1])),
        "log_loss": float(log_loss(y_test, proba, labels=[0, 1])),
        "class_names": ["Low Potential Dysgraphia", "Potential Dysgraphia"],
        "epochs_completed": len(hist.history.get("loss", [])), "seed": SEED,
        "split": "same saved image-level 70/15/15 split; participant independence unavailable",
        "note": "Fresh baseline run; compare generated metrics with the manuscript rather than assuming historical values are reproduced."
    }
    model.save(MODEL_DIR / "dysgraphia_end_to_end_cnn.keras")
    np.save(OUT / "y_test_true.npy", y_test); np.save(OUT / "y_test_pred.npy", pred); np.save(OUT / "y_test_proba.npy", proba)
    np.savetxt(OUT / "confusion_matrix.csv", confusion_matrix(y_test, pred, labels=[0, 1]), delimiter=",", fmt="%d")
    (OUT / "metrics.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    (OUT / "classification_report.json").write_text(json.dumps(classification_report(y_test, pred, labels=[0, 1], target_names=metrics["class_names"], output_dict=True, zero_division=0), indent=2), encoding="utf-8")
    print(json.dumps(metrics, indent=2))
    print(f"Saved independent dysgraphia baseline to {OUT}")

if __name__ == "__main__":
    main()
