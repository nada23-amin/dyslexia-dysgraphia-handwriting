"""
Reproduce the manuscript's component ablations for both tasks.

Variants:
  full                - complete preprocessing and training-only balancing/augmentation
  no_resampling       - retain the original training split without balancing/augmentation
  no_preprocessing    - grayscale + resize only; omit CLAHE, denoising, adaptive thresholding,
                        and deskewing; keep training-only resampling/augmentation

Each variant writes to outputs/ablation/<variant>/ so runs do not overwrite each other.
The script reports freshly computed metrics; it does not force results to match manuscript
numbers. Use the resulting files to verify or revise manuscript tables.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PYTHON = sys.executable
VARIANTS = ("full", "no_resampling", "no_preprocessing")


def run_command(label: str, command: list[str], mode: str) -> None:
    log_dir = ROOT / "outputs" / "ablation" / mode / "logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    log_path = log_dir / f"{label}.log"
    env = os.environ.copy()
    env["ABLATION_MODE"] = mode
    print(f"\n{'=' * 80}\nABLATION={mode} | {label}\n{'=' * 80}")
    with log_path.open("w", encoding="utf-8") as log:
        proc = subprocess.Popen(
            command, cwd=str(ROOT), env=env,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, encoding="utf-8", errors="replace"
        )
        assert proc.stdout is not None
        for line in proc.stdout:
            print(line, end="")
            log.write(line)
        code = proc.wait()
    if code:
        raise SystemExit(
            f"Experiment failed: mode={mode}, stage={label}, exit={code}. "
            f"Inspect {log_path}"
        )


def main() -> None:
    for mode in VARIANTS:
        variant_root = ROOT / "outputs" / "ablation" / mode
        variant_root.mkdir(parents=True, exist_ok=True)
        manifest = {
            "variant": mode,
            "seed": 42,
            "dyslexia": {
                "split": "image-level 70/15/15, same split seed",
                "no_resampling": mode == "no_resampling",
                "no_preprocessing": mode == "no_preprocessing",
            },
            "dysgraphia": {
                "split": "image-level 70/15/15, random_state=42",
                "no_resampling": mode == "no_resampling",
                "no_preprocessing": mode == "no_preprocessing",
            },
            "input_sources": {
                "dyslexia_raw_data": "DYSLEXIA_DATA_DIR if configured, otherwise data/raw/",
                "dysgraphia_raw_data": "DYSGRAPHIA_DATA_DIR if configured, otherwise data/dysgraphia_raw/",
                "pipeline_entrypoints": ["run_pipeline.py --dyslexia", "src/dysgraphia_pipeline.py"],
                "features_and_labels": "Regenerated by each variant under outputs/ablation/<variant>/",
            },
            "expected_output_root": str(variant_root),
            "note": (
                "Metrics are computed from the configured datasets and regenerated artifacts for "
                "this variant. They are not hard-coded. Compare the resulting tables and sample "
                "counts with the exact manuscript ablation tables before reporting."
            ),
        }
        (variant_root / "ablation_manifest.json").write_text(
            json.dumps(manifest, indent=2), encoding="utf-8"
        )

        # Run the entire Dyslexia pipeline under this isolated output root.
        run_command(
            "dyslexia_pipeline",
            [PYTHON, str(ROOT / "run_pipeline.py"), "--dyslexia"],
            mode,
        )
        # Dysgraphia is a self-contained end-to-end pipeline.
        run_command(
            "dysgraphia_pipeline",
            [PYTHON, str(ROOT / "src" / "dysgraphia_pipeline.py")],
            mode,
        )

    print(
        "\nAll ablation variants completed. Inspect outputs/ablation/<variant>/ "
        "and compare computed results with the manuscript before submission."
    )


if __name__ == "__main__":
    main()
